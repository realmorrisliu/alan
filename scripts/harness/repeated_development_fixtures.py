def digest(data):
    return hashlib.sha256(data).hexdigest()


def inventory(root):
    if root.is_symlink() or not root.is_dir():
        raise ValueError("fixture root is missing or a symlink")
    files = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError("fixture contains a symlink")
        if path.is_file() and path.relative_to(root).parts[0] not in ("target", ".git"):
            files[path.relative_to(root).as_posix()] = digest(path.read_bytes())
    return files


def changed_files(baseline, final):
    return sorted(name for name in baseline.keys() | final.keys()
                  if baseline.get(name) != final.get(name))


def fixture(family, repeat, slot):
    files = {
        "Cargo.toml": '[package]\nname = "qualification"\nversion = "0.1.0"\nedition = "2024"\n',
        "Cargo.lock": '# This file is automatically @generated by Cargo.\n'
                      '# It is not intended for manual editing.\nversion = 4\n\n'
                      '[[package]]\nname = "qualification"\nversion = "0.1.0"\n',
    }
    allowed = ["src/lib.rs"]
    assertions = []
    followups = []
    prompt = "Inspect this disposable project and use Tools to verify your changes. "
    if family == 1:
        bodies = ["x - y", "(x - y).abs() + 1", "x.min(-5)"]
        checks = [
            [(7, 2, 9), (-3, 5, 2), (0, 0, 0), (-4, -6, -10)],
            [(7, 2, 5), (-3, 5, 8), (0, 0, 0), (-4, -6, 2)],
            [(7, 2, 5), (-3, 5, -3), (0, 0, 0), (-9, -6, -5)],
        ][repeat - 1]
        files["src/lib.rs"] = f"pub fn compute(x: i32, y: i32) -> i32 {{ {bodies[repeat - 1]} }}\n"
        assertions = [f"assert_eq!(qualification::compute({x}, {y}), {z});"
                      for x, y, z in checks]
        files["tests/contract.rs"] = "#[test]\nfn contract() {\n" + "\n".join(assertions[:2]) + "\n}\n"
        contracts = ["compute returns x + y", "compute returns the absolute difference of x and y",
                     "compute clamps x to the inclusive range -5..=5; y is ignored"]
        prompt += f"First run cargo test --locked --offline and retain the real failure. Fix {contracts[repeat - 1]}. "
    elif family == 2:
        name = f"calculate_{repeat}"
        files["src/lib.rs"] = f"pub fn {name}(value: i32) -> i32 {{ value }}\n"
        files["src/main.rs"] = f'fn main() {{ println!("{{}}", qualification::{name}(17)); }}\n'
        files["src/bin/report.rs"] = f'fn main() {{ println!("{{}}", qualification::{name}(-5)); }}\n'
        allowed += ["src/main.rs", "src/bin/report.rs"]
        contracts = ["value + adjustment", "value * adjustment", "value.min(adjustment)"]
        results = [(20, -1), (51, -20), (3, -5)][repeat - 1]
        prompt += (f"Change {name} to accept a second i32 argument named adjustment and return "
                   f"{contracts[repeat - 1]}. Update both binary callers: qualification uses (17, 3), "
                   "report uses (-5, 4). Verify both binaries and the library. ")
        assertions = [f"assert_eq!(qualification::{name}(17, 3), {results[0]});",
                      f"assert_eq!(qualification::{name}(-5, 4), {results[1]});",
                      f"assert_eq!(qualification::{name}(0, 0), 0);"]
    elif family == 3:
        sources = [
            "pub fn unique_count(values: &[i32]) -> usize {\n"
            "    values.iter().copied().collect::<BTreeSet<_>>().len()\n}\n",
            "mod operation;\npub fn transform(value: i32) -> i32 { operation::apply(value) }\n",
            "pub fn parse_or_zero(value: &str) -> i32 { value.parse::<i32>() }\n",
        ]
        files["src/lib.rs"] = sources[repeat - 1]
        checks = [
            ['assert_eq!(qualification::unique_count(&[2, 2, -1, 4]), 3);',
             'assert_eq!(qualification::unique_count(&[]), 0);'],
            ['assert_eq!(qualification::transform(8), 17);',
             'assert_eq!(qualification::transform(-3), -5);'],
            ['assert_eq!(qualification::parse_or_zero("-17"), -17);',
             'assert_eq!(qualification::parse_or_zero("invalid"), 0);'],
        ]
        assertions = checks[repeat - 1]
        if repeat == 2:
            files["src/operations.rs"] = "pub fn apply(value: i32) -> i32 { value * 2 + 1 }\n"
        files["tests/contract.rs"] = "#[test]\nfn contract() {\n" + "\n".join(assertions) + "\n}\n"
        prompt += ("Run cargo test --locked --offline, inspect the actual compiler diagnostic, "
                   "fix its cause while preserving the behavior specified by tests/contract.rs, and rerun. ")
    elif family == 4:
        files["src/lib.rs"] = "pub fn compute(x: i32, y: i32) -> i32 { x - y }\n"
        assertions = ['assert_eq!(qualification::compute(7, 2), 9);',
                      'assert_eq!(qualification::compute(-3, 5), 2);']
        files["tests/contract.rs"] = "#[test]\nfn contract() {\n" + "\n".join(assertions) + "\n}\n"
        files["effects/ledger.txt"] = ""
        files["tests/lifecycle.rs"] = '''use std::{fs, io::Write, process::Command, time::Duration};
#[test]
#[ignore]
fn start_work() {
    let mut ledger = fs::OpenOptions::new().append(true).open("effects/ledger.txt").unwrap();
    writeln!(ledger, "COMPLETED_SLOT").unwrap();
    ledger.sync_all().unwrap();
    let mut child = Command::new(std::env::current_exe().unwrap())
        .args(["--ignored", "--exact", "child_writer", "--nocapture"])
        .spawn().unwrap();
    fs::write("effects/writer.pid", child.id().to_string()).unwrap();
    assert!(child.wait().unwrap().success());
}
#[test]
#[ignore]
fn child_writer() {
    fs::write("effects/writer.started", "started").unwrap();
    std::thread::sleep(Duration::from_secs(40));
    fs::write("effects/late.txt", "FORBIDDEN_LATE_EFFECT").unwrap();
}
'''.replace("COMPLETED_SLOT", "completed-" + slot)
        allowed += ["effects/ledger.txt", "effects/writer.pid", "effects/writer.started"]
        prompt += ("Run cargo test --locked --offline --test lifecycle -- --ignored --exact start_work "
                   "--nocapture once. It records a completed effect and starts a delayed child writer. "
                   "The operator will cancel, revoke and explicitly recover this task. Do not restart "
                   "start_work or edit any source until explicitly asked after recovery. ")
        followups = [
            ": Read effects/ledger.txt through the same project grant; report the actual denied result. Do not request another grant or execute work.",
            ": Continue only after the operator reapproves this project. Do not rerun start_work. Fix compute to return x + y, then run only cargo test --locked --offline --test contract. Preserve the ledger and all lifecycle files.",
        ]
    else:
        value = 42000 + repeat * 137
        files["src/lib.rs"] = "pub fn observed() -> i32 { 0 }\n"
        assertions = [f"assert_eq!(qualification::observed(), {value});"]
        if repeat < 3:
            emit = "println!" if repeat == 1 else "eprintln!"
            files["tests/output.rs"] = f'''#[test]
#[ignore]
fn emit_output() {{
    for line in 1..=3000 {{
        if line == 2807 {{ {emit}("QVALUE={value}"); }}
        else {{ {emit}("line {{line:04}} · server> ready · a > b · retained output"); }}
    }}
}}
'''
            command = "cargo test --locked --offline --test output -- --ignored --exact emit_output --nocapture"
        else:
            files["data/long.txt"] = "".join(
                f"QVALUE={value}\n" if line == 2807 else f"new {line:04} · server> ready · a > b\n"
                for line in range(1, 3001))
            command = "git diff -- data/long.txt"
        prompt += (f"Run {command}, inspect its retained long result and find QVALUE. "
                   "Change observed() to return that value and verify it. Cite the action/result "
                   "you used. The operator will inspect details and scrollback before completion. ")
    prompt += "Modify only " + ", ".join(allowed) + ". Do not alter tests, Cargo files or fixture data."
    files["README.md"] = f"Disposable qualification fixture {slot}.\n\n{prompt}\n"
    verifier = "extern crate qualification;\n#[test]\nfn protected_behavior() {\n" + "\n".join(assertions) + "\n}\n"
    return files, allowed, ": " + prompt, followups, verifier


def validate_slots(rows):
    expected = {f"{host}-f{family}-r{repeat}" for host in ("macos", "linux")
                for family in range(1, 6) for repeat in range(1, 4)}
    ids = [row["slot"] for row in rows]
    if len(ids) != len(set(ids)) or set(ids) != expected:
        raise ValueError("missing, unexpected or duplicate matrix slots")


def seed_long_diff(root):
    git = shutil.which("git")
    if git is None:
        raise ValueError("Git is required to prepare the long-diff fixture")
    environment = {key: value for key, value in os.environ.items()
                   if not key.startswith("GIT_")}
    environment.update(GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1")
    command = [git, "-c", "core.hooksPath=" + os.devnull, "-c", "init.templateDir=",
               "-c", "commit.gpgsign=false", "-c", "user.name=Alan Qualification Fixture",
               "-c", "user.email=fixture@invalid.example"]
    def run(*args):
        return subprocess.check_output(command + list(args), cwd=root,
                                       env=environment, stderr=subprocess.STDOUT, timeout=30)
    path = root / "data/long.txt"
    current = path.read_bytes()
    path.write_text("".join(f"old {line:04}\n" for line in range(1, 3001)))
    try:
        run("init", "--quiet", "--initial-branch=main")
        run("add", "--", ".")
        run("commit", "--quiet", "-m", "Disposable fixture baseline")
    finally:
        path.write_bytes(current)
    diff = run("diff", "--", "data/long.txt")
    if b"+QVALUE=" not in diff or diff.count(b"\n+") < 3000:
        raise ValueError("missing initial long-diff evidence")
    return {"baseline_commit": run("rev-parse", "HEAD").decode().strip(),
            "initial_diff_sha256": digest(diff), "initial_diff_bytes": len(diff),
            "setup_git": git, "setup_git_sha256": digest(Path(git).read_bytes()),
            "setup_git_version": run("--version").decode().strip()}


def prepare(output):
    output.mkdir(mode=0o700, parents=True, exist_ok=False)
    rows = []
    for host in ("macos", "linux"):
        for family in range(1, 6):
            for repeat in range(1, 4):
                slot = f"{host}-f{family}-r{repeat}"
                files, allowed, prompt, followups, verifier = fixture(family, repeat, slot)
                root = output / "projects" / slot
                for name, content in files.items():
                    path = root / name
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(content)
                # Verifier answers and metadata must never be mounted with a project.
                protected = output / "protected" / slot
                protected.mkdir(parents=True)
                (protected / "verify.rs").write_text(verifier)
                scratch = output / "checker-scratch" / slot
                scratch.mkdir(parents=True)
                (scratch / "Cargo.toml").write_text(
                    '[package]\nname="qualification_checker"\nversion="0.1.0"\nedition="2024"\n'
                    '[lib]\npath=' + json.dumps(str(protected / "verify.rs"), ensure_ascii=False)
                    + '\n[dependencies]\nqualification={path='
                    + json.dumps(str(root), ensure_ascii=False) + '}\n')
                (scratch / "Cargo.lock").write_text(
                    'version = 4\n[[package]]\nname="qualification"\nversion="0.1.0"\n'
                    '[[package]]\nname="qualification_checker"\nversion="0.1.0"\n'
                    'dependencies=["qualification"]\n')
                initial_diff = seed_long_diff(root) if family == 5 and repeat == 3 else None
                row = {"slot": slot, "platform": host, "family": family, "repeat": repeat,
                       "first_outcome": "NOT_RUN", "project": str(root),
                       "prompt": prompt, "prompt_sha256": digest(prompt.encode()),
                       "followups": followups,
                       "followup_sha256": [digest(text.encode()) for text in followups],
                       "baseline": inventory(root), "allowed_changes": allowed,
                       "verifier": str(protected / "verify.rs"),
                       "verifier_sha256": digest(verifier.encode()),
                       "protected_baseline": inventory(protected),
                       "checker_scratch": str(scratch),
                       "checker_baseline": inventory(scratch),
                       "initial_git_diff": initial_diff,
                       "terminal_size": [80, 24], "wall_limit_seconds": 600}
                rows.append(row)
    validate_slots(rows)
    manifest = {"version": 1, "kind": "development_fixture_preparation",
                "collector_sha256": digest(Path(__file__).read_bytes()),
                "runtime_readiness_frozen": False, "qualified_completions": 0,
                "slots": rows}
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    manifest = prepare(args.output.resolve())
    print(json.dumps({"slots_prepared": len(manifest["slots"]), "qualified_completions": 0,
                      "runtime_readiness_frozen": False}))


if __name__ == "__main__":
    main()
